#!/usr/bin/env python3
"""Fill skills/iphone-duo-patterns/ from the repository, so the skill carries no rule of its own and runs on its own.

references/ — copied (with repo-relative links rewritten to the GitHub repository, and matrix images copied alongside):
  patterns/DECISION-TABLE.md      → decision-table.md
  patterns/TAXONOMY.md            → taxonomy.md
  patterns/<pattern>.md           → patterns/<pattern>.md   (the shipped pattern pages)
  Sources/Patterns/<Pattern>.swift → patterns/<Pattern>.swift (their reference implementations; links point here)
  verification/matrices/<m>.png   → patterns/matrices/<m>.png
A repository path named in backticks in a copied page becomes a link to GitHub, since the installed skill has no raw/.
LICENSE → the skill's root (beside SKILL.md) and the plugin's root (plugins/duo-migration/LICENSE): the plugin travels
alone.
Generated:
  raw/metrics.json                → metrics.md
Hand-written, condensed from raw/ with citations, and left alone here: apple.md, simulator.md, detectors-static.md.

tools/ — the capture scripts, the tap runner and the detectors, copied verbatim, so an agent using the skill outside
this repository captures and checks poses the same way (references/simulator.md says how):
  scripts/capture-app.sh, scripts/capture-corpus-app.sh, scripts/capture-corpus-flow.sh, scripts/progress.py,
  scripts/same-screen.py                                       → tools/
  Tap/project.yml, Tap/DuoTapUITests/                          → tools/tap/
  Sources/DuoDetectors/, Sources/duo-detect/                   → tools/detect/Sources/ (with a Package.swift of its own)

Then the whole skill is mirrored into the duo-migration plugin (plugins/duo-migration/skills/iphone-duo-patterns/), so
installing the plugin installs the skill with its pane.

    python3 scripts/sync-skill-references.py          # write
    python3 scripts/sync-skill-references.py --check  # exit 1 if anything is out of date (CI)
"""
import json
import os
import subprocess
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "iphone-duo-patterns"
PLUGIN_SKILL = ROOT / "plugins" / "duo-migration" / "skills" / "iphone-duo-patterns"
LOCAL = (".build", ".swiftpm", "build")   # a local build of the tools, git-ignored
REPO = "https://github.com/3nchiridion/duo-kit/blob/main/"
PAGES = ["fold-aligned-split", "even-grid", "reflowing-columns", "arrangement"]
POSES = ["closed", "closed-sideways", "book", "laptop", "tent", "flat-sideways", "flat-upright"]


def header(src):
    return f"<!-- Generated by scripts/sync-skill-references.py from {src}. Edit the source, then rerun it. -->\n\n"


def beside_pages(src):
    """Whether the copy of src lands in references/patterns/, next to the pages (a page does; the decision table and the
    taxonomy land in references/)."""
    return src.startswith("patterns/") and pathlib.Path(src).stem in PAGES


def relink(text, src):
    """Repo-relative links → matrix images next to the copy, everything else → the repository on GitHub."""
    base = (ROOT / src).parent

    def fix(m):
        label, target = m.group(1), m.group(2)
        if re.match(r"[a-z]+:|#", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        resolved = (base / path).resolve().relative_to(ROOT).as_posix()
        if resolved.startswith("verification/matrices/") and resolved.endswith(".png"):
            return f"{label}(matrices/{pathlib.Path(resolved).name})"
        if (resolved.startswith("patterns/") and pathlib.Path(resolved).stem in PAGES) or (
                resolved.startswith("Sources/Patterns/") and resolved.endswith(".swift")):
            return f"{label}({'' if beside_pages(src) else 'patterns/'}{pathlib.Path(resolved).name})"
        return f"{label}({REPO}{resolved}{'#' + anchor if anchor else ''})"

    text = re.sub(r"(!?\[[^\]]*\])\(([^)\s]+)\)", fix, text)
    return code_paths(text, src)


ROOTS = ("raw/", "patterns/", "verification/", "Sources/", "scripts/", "Examples/", "Tests/", "docs/")
ROOT_FILES = {"EVAL.md", "README.md"}


def ignored(path):
    return subprocess.run(["git", "-C", str(ROOT), "check-ignore", "-q", path]).returncode == 0


def code_paths(text, src):
    """A repository path named in backticks (`raw/metrics.json`) is not in the installed skill: link it to GitHub, or,
    for one of the pattern pages or a file of the skill itself, to its copy in the skill. Paths git ignores (a local
    corpus clone) stay as they are, so the output is the same on any checkout. Lines inside ``` fences and paths
    already inside a link are left alone."""
    def fix(m):
        before, path = m.group(1), m.group(2)
        clean = path.rstrip("/.,;:")
        if clean.startswith("skills/iphone-duo-patterns/") and (ROOT / clean).exists():
            here = "references/patterns" if beside_pages(src) else "references"
            return f"{before}[`{path}`]({os.path.relpath(clean[len('skills/iphone-duo-patterns/'):], here)})"
        if not (clean.startswith(ROOTS) or clean in ROOT_FILES) or not (ROOT / clean).exists() or ignored(clean):
            return m.group(0)
        if clean.startswith("patterns/") and pathlib.Path(clean).stem in PAGES:
            target = f"{'' if beside_pages(src) else 'patterns/'}{pathlib.Path(clean).name}"
        else:
            target = (REPO.replace("/blob/", "/tree/") if (ROOT / clean).is_dir() else REPO) + clean
        return f"{before}[`{path}`]({target})"

    out, fenced = [], False
    for line in text.split("\n"):
        if line.lstrip().startswith("```"):
            fenced = not fenced
        out.append(line if fenced else re.sub(r"(^|[^\[`])`([^`\s]+)`(?!\])", fix, line))
    return "\n".join(out)


def metrics():
    d = json.loads((ROOT / "raw/metrics.json").read_text())
    def extent(r):
        f = r["frame"]
        lo, size = (f["x"], f["w"]) if f["h"] > f["w"] else (f["y"], f["h"])
        return f"{'x' if f['h'] > f['w'] else 'y'} {lo:g}–{lo + size:g} ({'active' if r['isActive'] else 'inactive'})"

    rows = []
    for pose in POSES:
        s = d[pose]["settled"]
        inset = ", ".join(f"{k} {v:g}" for k, v in s["scene"]["windowSafeArea"].items() if v)
        edge = s.get("toolbarVerticalEdge")
        div = "; ".join(extent(r) for r in s["divisions"]) or "none"
        occ = "; ".join(f"{r['frame']['w']:g}×{r['frame']['h']:g} at ({r['frame']['x']:.0f},{r['frame']['y']:.0f})"
                        for r in s["occlusions"] if r["isActive"]) or "none"
        hinge = d[pose].get("hingeAtPose") or {}
        at = f"{hinge['status']} {hinge['angleDegrees']:.1f}°" if hinge.get("angleDegrees") is not None else "not read"
        rows.append(f"| {pose} | {s['window']['w']:g} × {s['window']['h']:g} | {inset} | {s['hSizeClass']}/{s['vSizeClass']} | "
                    f"{'none' if edge in (None, 'nil') else edge} | {div} | {occ} | {at} |")
    return (header("raw/metrics.json") + "# Measured pose metrics\n\n"
            "iPhone Duo simulator, iOS 27.1. Points, window coordinates; division frames include their 20 pt margins. "
            "Source: `raw/metrics.json` (settled sample after launch), notes in `raw/METRICS-NOTES.md`.\n\n"
            "| Pose | Window | Safe area | Classes h/v | Vertical bar | Division | Active occlusions | Hinge |\n"
            "|---|---|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")


DETECT_PACKAGE = """// swift-tools-version: 6.0
// Generated by scripts/sync-skill-references.py: the duo-kit detectors and duo-detect, with no other dependency.
//   swift run --package-path <skill>/tools/detect duo-detect <captures-dir> [--markdown out.md]
import PackageDescription

let package = Package(
    name: "duo-detect",
    platforms: [.macOS(.v14)],
    products: [.executable(name: "duo-detect", targets: ["duo-detect"])],
    targets: [
        .target(name: "DuoDetectors", resources: [.copy("Resources/poses.json")]),
        .executableTarget(name: "duo-detect", dependencies: ["DuoDetectors"]),
    ]
)
"""

TOOLS_README = """<!-- Generated by scripts/sync-skill-references.py. Edit the sources in the repository, then rerun it. -->

# tools/

Copies of the duo-kit repository's capture and detection tools, so the skill works outside it. How to use them:
`../references/simulator.md`.

| Here | Repository source |
|---|---|
| `capture-app.sh` | `scripts/capture-app.sh` |
| `capture-corpus-app.sh` | `scripts/capture-corpus-app.sh` |
| `capture-corpus-flow.sh` | `scripts/capture-corpus-flow.sh` |
| `progress.py` | `scripts/progress.py` |
| `same-screen.py` | `scripts/same-screen.py` |
| `tap/` | `Tap/` (XcodeGen spec and the XCUITest runner; `xcodegen generate` makes the project) |
| `detect/` | `Sources/DuoDetectors`, `Sources/duo-detect` (Package.swift generated) |
"""


def plan():
    out = {
        "references/decision-table.md": header("patterns/DECISION-TABLE.md") + relink((ROOT / "patterns/DECISION-TABLE.md").read_text(), "patterns/DECISION-TABLE.md"),
        "references/taxonomy.md": header("patterns/TAXONOMY.md") + relink((ROOT / "patterns/TAXONOMY.md").read_text(), "patterns/TAXONOMY.md"),
        "references/metrics.md": code_paths(metrics(), "raw/metrics.json"),
    }
    for page in PAGES:
        src = f"patterns/{page}.md"
        if (ROOT / src).exists():
            out[f"references/patterns/{page}.md"] = header(src) + relink((ROOT / src).read_text(), src)
    for f in sorted((ROOT / "Sources/Patterns").glob("*.swift")):
        out[f"references/patterns/{f.name}"] = f.read_bytes()
    for m in sorted((ROOT / "verification/matrices").glob("*.png")):
        out[f"references/patterns/matrices/{m.name}"] = m.read_bytes()

    out["LICENSE"] = (ROOT / "LICENSE").read_bytes()
    out["tools/README.md"] = TOOLS_README
    for script in ["capture-app.sh", "capture-corpus-app.sh", "capture-corpus-flow.sh", "progress.py", "same-screen.py"]:
        out[f"tools/{script}"] = (ROOT / "scripts" / script).read_bytes()
    out["tools/tap/project.yml"] = (ROOT / "Tap/project.yml").read_bytes()
    for f in sorted((ROOT / "Tap/DuoTapUITests").rglob("*.swift")):
        out[f"tools/tap/DuoTapUITests/{f.relative_to(ROOT / 'Tap/DuoTapUITests').as_posix()}"] = f.read_bytes()
    out["tools/detect/Package.swift"] = DETECT_PACKAGE
    for target in ["DuoDetectors", "duo-detect"]:
        for f in sorted((ROOT / "Sources" / target).rglob("*")):
            if f.is_file() and f.name != ".DS_Store":
                out[f"tools/detect/Sources/{target}/{f.relative_to(ROOT / 'Sources' / target).as_posix()}"] = f.read_bytes()
    return out


def mirror(check):
    """The skill, as it stands after the step above, copied into the plugin; what the skill no longer has goes."""
    stale = []
    wanted = {}
    for f in sorted(SKILL.rglob("*")):
        rel = f.relative_to(SKILL)
        if f.is_file() and f.name != ".DS_Store" and not any(part in LOCAL for part in rel.parts):
            wanted[rel.as_posix()] = f
    for rel, f in wanted.items():
        target = PLUGIN_SKILL / rel
        if target.exists() and target.read_bytes() == f.read_bytes() and target.stat().st_mode == f.stat().st_mode:
            continue
        stale.append(f"plugin:{rel}")
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(f.read_bytes())
            target.chmod(f.stat().st_mode & 0o777)
    for f in sorted(PLUGIN_SKILL.rglob("*")) if PLUGIN_SKILL.exists() else []:
        rel = f.relative_to(PLUGIN_SKILL).as_posix()
        if f.is_file() and f.name != ".DS_Store" and rel not in wanted:
            stale.append(f"plugin:{rel}")
            if not check:
                f.unlink()
    return stale


def main():
    check = "--check" in sys.argv
    stale = []
    # The plugin travels on its own (the marketplace copies only its folder), so it carries the license too.
    plugin_license = PLUGIN_SKILL.parents[1] / "LICENSE"
    if not plugin_license.exists() or plugin_license.read_bytes() != (ROOT / "LICENSE").read_bytes():
        stale.append("plugin:LICENSE (plugin root)")
        if not check:
            plugin_license.write_bytes((ROOT / "LICENSE").read_bytes())
    files = plan()
    for rel, content in files.items():
        target = SKILL / rel
        data = content.encode() if isinstance(content, str) else content
        if target.exists() and target.read_bytes() == data:
            continue
        stale.append(rel)
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            if rel.endswith((".sh", ".py")):
                target.chmod(0o755)
    # A tool removed from the repository goes from the skill too.
    for f in sorted((SKILL / "tools").rglob("*")) if (SKILL / "tools").exists() else []:
        rel = f.relative_to(SKILL).as_posix()
        if any(part in LOCAL for part in f.relative_to(SKILL).parts):
            continue   # a local build of the copy, git-ignored
        if f.is_file() and f.name != ".DS_Store" and rel not in files:
            stale.append(rel)
            if not check:
                f.unlink()
    stale += mirror(check)
    if check and stale:
        print("out of date: " + ", ".join(stale) + "\nrun: python3 scripts/sync-skill-references.py")
        sys.exit(1)
    print(("up to date" if not stale else ("would update " if check else "updated ") + ", ".join(stale)))


if __name__ == "__main__":
    main()
